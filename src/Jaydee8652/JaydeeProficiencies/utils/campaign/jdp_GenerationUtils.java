    public static StarSystemGenerator.CustomConstellationParams normaliseParams(StarSystemGenerator.CustomConstellationParams params) {
        params = normaliseStarTypes(params);
        params = normaliseSystemTypes(params);
        return params;
    }
    public static StarSystemGenerator.CustomConstellationParams normaliseStarTypes(StarSystemGenerator.CustomConstellationParams params) {
        params.starTypes = new ArrayList<>();
        var starTypes = NORMAL_STAR_TYPES;
        Collections.shuffle(starTypes);
        params.starTypes.addAll(starTypes);
        return params;
    }
    public static StarSystemGenerator.CustomConstellationParams normaliseSystemTypes(StarSystemGenerator.CustomConstellationParams params) {
        params.systemTypes = new ArrayList<>();
        var systemTypes = NORMAL_SYSTEM_TYPES;
        Collections.shuffle(systemTypes);
        params.systemTypes.addAll(systemTypes);
        return params;
    }

    public static StarSystemAPI generateSystem(StarSystemGenerator.CustomConstellationParams params) {
        params.numStars = 1;

        StarSystemGenerator gen = new StarSystemGenerator(params);
        var constellation = gen.generate();
        return constellation.getSystems().get(0);
    }

    public static void hideSystem(StarSystemAPI system) {
        system.getAutogeneratedJumpPointsInHyper().forEach(loc -> loc.addTag(Tags.STAR_HIDDEN_ON_MAP));
    }

    public static PlanetAPI addStar(StarSystemAPI system, String id, SectorEntityToken focus, String name, String type, float angle, float radius, float orbitRadius, float orbitDays) {
        PlanetSpecAPI starSpec = null;
        for (PlanetSpecAPI spec : Global.getSettings().getAllPlanetSpecs()) if (spec.getPlanetType().equals(type)) starSpec = spec;
        if (starSpec == null) return null;

        StarGenDataSpec starData = (StarGenDataSpec) Global.getSettings().getSpec(StarGenDataSpec.class, starSpec.getPlanetType(), false);
        if (radius == -1) radius = getRadius(starData.getMinRadius(), starData.getMaxRadius());

        PlanetAPI star = system.addPlanet(id, focus, name, starSpec.getPlanetType(), angle, radius, orbitRadius, orbitDays);

        float corona = radius * (starData.getCoronaMult() + starData.getCoronaVar() * (random.nextFloat() - 0.5f));
        if (corona < starData.getCoronaMin()) corona = starData.getCoronaMin();
        system.addCorona(star, corona,  // corona radius, from star edge
                starData.getSolarWind(),
                (float) (starData.getMinFlare() + (starData.getMaxFlare() - starData.getMinFlare()) * random.nextFloat()),
                starData.getCrLossMult());

        if (star.getSpec().getPlanetType().equals(StarTypes.BLACK_HOLE)) {
            StarCoronaTerrainPlugin coronaPlugin = Misc.getCoronaFor(star);
            if (coronaPlugin != null) system.removeEntity(coronaPlugin.getEntity());

            SectorEntityToken eventHorizon = system.addTerrain(Terrain.EVENT_HORIZON,
                    new StarCoronaTerrainPlugin.CoronaParams(star.getRadius() + corona, (star.getRadius() + corona) / 2f,
                            star, starData.getSolarWind(),
                            (float) (starData.getMinFlare() + (starData.getMaxFlare() - starData.getMinFlare()) * random.nextFloat()),
                            starData.getCrLossMult()));
            eventHorizon.setCircularOrbit(star, 0, 0, 100);
        }

        if (star.getSpec().getPlanetType().equals(StarTypes.NEUTRON_STAR)) {
            StarCoronaTerrainPlugin coronaPlugin = Misc.getCoronaFor(star);
            if (coronaPlugin != null) system.removeEntity(coronaPlugin.getEntity());

            system.addCorona(star,
                    300, // radius
                    3, // wind
                    0, // flares
                    3); // cr loss

            SectorEntityToken eventHorizon = system.addTerrain(Terrain.PULSAR_BEAM,
                    new StarCoronaTerrainPlugin.CoronaParams(star.getRadius() + corona, (star.getRadius() + corona) / 2f,
                            star, starData.getSolarWind(),
                            starData.getMinFlare() + (starData.getMaxFlare() - starData.getMinFlare()) * random.nextFloat(),
                            starData.getCrLossMult()));
            eventHorizon.setCircularOrbit(star, 0, 0, 100);
        }
        return star;
    }

    public static boolean isPointNearCore(Vector2f point) {
        return isPointWithinBounds(point, -24000f, 12000f, -18000f, 12000f);
    }

    public static boolean isPointWithinBounds(Vector2f point, Float definedMinX, Float definedMaxX, Float definedMinY, Float definedMaxY) {
        return (((definedMinX == null || point.x >= definedMinX) && (definedMaxX == null || point.x <= definedMaxX)) &&
                ((definedMinY == null || point.y >= definedMinY) && (definedMaxY == null || point.y <= definedMaxY)));
    }

    public static boolean doCirclesIntersect(Vector2f centerA, float radiusA, Vector2f centerB, float radiusB) {
        return Math.hypot(centerA.x - centerB.x, centerA.y - centerB.y) <= (radiusA + radiusB);
    }

    public static Vector2f findSpace(StarSystemAPI system, SectorEntityToken newEntity) {
        List<Float> xCoords = system.getAllEntities().stream().map(SectorEntityToken::getLocation).map(Vector2f::getX).toList();
        List<Float> yCoords = system.getAllEntities().stream().map(SectorEntityToken::getLocation).map(Vector2f::getY).toList();

        float lowerBoundX = xCoords.stream().min(Float::compareTo).orElseThrow();
        float upperBoundX = xCoords.stream().max(Float::compareTo).orElseThrow();

        float lowerBoundY = yCoords.stream().min(Float::compareTo).orElseThrow();
        float upperBoundY = yCoords.stream().max(Float::compareTo).orElseThrow();

        for (int i = 0; i < 15000; i++) {
            Vector2f point = new Vector2f(Math.round((Math.random() * (upperBoundX - lowerBoundX)) + lowerBoundX), Math.round((Math.random() * (upperBoundY - lowerBoundY)) + lowerBoundY));

            boolean doesPointIntersectWithAnyEntities = system.getAllEntities().stream().anyMatch(entity -> doCirclesIntersect(point, newEntity.getRadius() + 50, entity.getLocation(), entity.getRadius() + 50));

            if (!doesPointIntersectWithAnyEntities) return point;
        }
        return new Vector2f(20000,20000);
    }

    public static List<Constellation> getConstellations(int degreesOfFreedom) {
        List<Constellation> constellations = (Global.getSector().getStarSystems().stream().map(StarSystemAPI::getConstellation).filter(Objects::nonNull).distinct().toList()).stream().sorted(Comparator.comparingDouble(c -> -Misc.getDistanceLY(c.getLocation(), new Vector2f(0, 0)))).collect(Collectors.toList());

        if (degreesOfFreedom == 0  || degreesOfFreedom == 1) constellations = constellations.stream().filter(c -> c.getSystems().stream().allMatch(s -> s.getLastPlayerVisitTimestamp() == 0L)).toList();
        if (degreesOfFreedom == 0) constellations = constellations.stream().filter(c -> c.getSystems().stream().noneMatch(s -> s.hasTag("$jdp_postgenSystem"))).toList();
        return constellations;
    }

    public static StarSystemAPI findInterestingSystem(Set<StarSystemAPI> exclude, Random random) {
        Set<PlanetAPI> planets = new HashSet<>();
        if (exclude != null) exclude.forEach(s -> planets.addAll(s.getPlanets()));
        var planet = DerelictThemeGenerator.findInterestingPlanet(Global.getSector().getStarSystems(), planets, false, true, random).getStarSystem();
        while (planet.hasTag(Tags.NOT_RANDOM_MISSION_TARGET)) DerelictThemeGenerator.findInterestingPlanet(Global.getSector().getStarSystems(), planets, false, true, random).getStarSystem();
        return planet;
    }

    public static boolean shuffleLocation(StarSystemAPI newSystem, Boolean joinConstellation, Float definedMinX, Float definedMaxX, Float definedMinY, Float definedMaxY) {
        //Will attempt to join an existing constellation, and will prefer one that matches the age and type of the system
        //Can handle null defined bounds
        if (joinConstellation) {
            StarAge age;
            Constellation.ConstellationType type;
            Constellation systemConstellation = newSystem.getConstellation();

            if (systemConstellation != null) {
                age = newSystem.getConstellation().getAge();
                type = newSystem.getConstellation().getType();
            } else {
                age = null;
                type = null;
            }

            int degreesOfFreedom = 0;
            List<Constellation> constellations = getConstellations(degreesOfFreedom);
            if (!(age == null || type == null)) constellations = constellations.stream().filter(c -> c.getSystems().stream().allMatch(s -> s.getConstellation().getAge() == age && s.getConstellation().getType() == type)).toList();

            while (constellations.isEmpty()) {
                degreesOfFreedom++;
                constellations = getConstellations(degreesOfFreedom);
                if (degreesOfFreedom <= 2) if (!(age == null || type == null)) constellations = constellations.stream().filter(c -> c.getSystems().stream().allMatch(s -> s.getConstellation().getAge() == age && s.getConstellation().getType() == type)).toList();
                if (degreesOfFreedom == 4) {
                    log.warn("JDP_RETROGEN_EVENTS: 		[CONTINGENCY] No valid constellations found at shuffleLocation");
                    return false;
                }
            }

            for (Constellation constellation : constellations) {
                List<Float> xCoords = constellation.getSystems().stream().map(StarSystemAPI::getLocation).map(Vector2f::getX).toList();
                List<Float> yCoords = constellation.getSystems().stream().map(StarSystemAPI::getLocation).map(Vector2f::getY).toList();

                float minX = xCoords.stream().min(Float::compareTo).orElseThrow();
                float maxX = xCoords.stream().max(Float::compareTo).orElseThrow();
                float lowerBoundX = minX - 500;
                float upperBoundX = maxX + 500;

                float minY = yCoords.stream().min(Float::compareTo).orElseThrow();
                float maxY = yCoords.stream().max(Float::compareTo).orElseThrow();
                float lowerBoundY = minY - 500;
                float upperBoundY = maxY + 500;

                for (int i = 0; i < 15000; i++) {
                    Vector2f point = new Vector2f(Math.round((Math.random() * (upperBoundX - lowerBoundX)) + lowerBoundX), Math.round((Math.random() * (upperBoundY - lowerBoundY)) + lowerBoundY));

                    boolean doesPointIntersectWithAnySystems = constellation.getSystems().stream().anyMatch(system -> doCirclesIntersect(point, newSystem.getMaxRadiusInHyperspace() + 50, system.getLocation(), system.getMaxRadiusInHyperspace() + 50));

                    if (!doesPointIntersectWithAnySystems && !isPointNearCore(point) && isPointWithinBounds(point, definedMinX, definedMaxX, definedMinY, definedMaxY)) {
                        newSystem.setConstellation(constellation);
                        constellation.getSystems().add(newSystem);
                        newSystem.getLocation().set(point);
                        log.info("JDP_RETROGEN_EVENTS: 		[CONTINGENCY] SHUFFLE SUCCESS (JOIN CONSTELLATION TRUE)");

                        return true;
                    }
                }
            }
            //Will not attempt to join an existing constellation, placed somewhere within the bounds defined
            //Can handle null defined bounds
        } else {
            for (int i = 0; i < 15000; i++) {
                Vector2f point = new Vector2f(Math.round((Math.random() * (definedMaxX - definedMinX)) + definedMinX), Math.round((Math.random() * (definedMaxY - definedMinY)) + definedMinY));

                boolean doesPointIntersectWithAnySystems = Global.getSector().getStarSystems().stream().anyMatch(system -> doCirclesIntersect(point, newSystem.getMaxRadiusInHyperspace() + 50, system.getLocation(), system.getMaxRadiusInHyperspace() + 50));

                if (!doesPointIntersectWithAnySystems) {
                    newSystem.getLocation().set(point);
                    log.info("JDP_RETROGEN_EVENTS: 		[CONTINGENCY] SHUFFLE SUCCESS (JOIN CONSTELLATION FALSE)");

                    return true;
                }
            }
        }
        //Backup, will attempt to move the system to somewhere within the sector. Has a small chance to end up in the abyss.
        //Can handle null defined bounds
        for (int i = 0; i < 150000; i++) {
            Vector2f point = new Vector2f(
                    Math.round((Math.random() * (78000f + 78000f)) - 78000f),
                    Math.round((Math.random() * (48000f + 48000f)) - 48000f)
            );

            boolean doesPointIntersectWithAnySystems = Global.getSector().getStarSystems().stream()
                    .anyMatch(system -> doCirclesIntersect(point, newSystem.getMaxRadiusInHyperspace() + 50, system.getLocation(), system.getMaxRadiusInHyperspace() + 50));

            if (!doesPointIntersectWithAnySystems && !isPointNearCore(point) && isPointWithinBounds(point, definedMinX, definedMaxX, definedMinY, definedMaxY)) {
                newSystem.getLocation().set(point);
                log.info("JDP_RETROGEN_EVENTS: 		[CONTINGENCY] SHUFFLE SUCCESS (LAST RESORT SHUFFLE)");

                return true;
            }
        }
        log.info("JDP_RETROGEN_EVENTS: 		[CONTINGENCY] FAILED TO SHUFFLE");
        return false;
    }
